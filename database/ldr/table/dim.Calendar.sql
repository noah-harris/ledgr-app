CREATE TABLE [dim].[Calendar] (
    [Date] DATE NOT NULL PRIMARY KEY,
    [DayOfWeek] TINYINT NOT NULL,
    [DayOfMonth] TINYINT NOT NULL,
    [DayOfYear] SMALLINT NOT NULL,
    [WeekOfYear] TINYINT NOT NULL,
    [Month] TINYINT NOT NULL,
    [Quarter] TINYINT NOT NULL,
    [Year] SMALLINT NOT NULL,
    [DayName] VARCHAR(10) NOT NULL,
    [DayNameShort] CHAR(3) NOT NULL,
    [MonthName] VARCHAR(10) NOT NULL,
    [MonthNameShort] CHAR(3) NOT NULL,
    [MonthYear] CHAR(7) NOT NULL,
    [QuarterLabel] CHAR(7) NOT NULL,
    [MonthKey] INT NOT NULL,
    [QuarterKey] INT NOT NULL,
    [YearKey] SMALLINT NOT NULL,
    [FiscalMonth] TINYINT NOT NULL,
    [FiscalQuarter] TINYINT NOT NULL,
    [FiscalYear] SMALLINT NOT NULL,
    [FiscalYearLabel] CHAR(6) NOT NULL,
    [IsWeekend] BIT NOT NULL,
    [IsWeekday] BIT NOT NULL,
    [IsHoliday] BIT NOT NULL,
    [HolidayName] VARCHAR(50) NULL,
    [IsBusinessDay] BIT NOT NULL,
    [IsLeapYear] BIT NOT NULL,
    [IsLastDayOfMonth] BIT NOT NULL,
    [IsFirstDayOfMonth] BIT NOT NULL,
    [FirstDayOfMonth] DATE NOT NULL,
    [LastDayOfMonth] DATE NOT NULL,
    [FirstDayOfQuarter] DATE NOT NULL,
    [LastDayOfQuarter] DATE NOT NULL,
    [FirstDayOfYear] DATE NOT NULL,
    [LastDayOfYear] DATE NOT NULL
);